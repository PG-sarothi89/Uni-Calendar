package unitrack.service;

import unitrack.model.*;
import unitrack.repository.ConsultancyRepository;
import unitrack.repository.DataStore;

import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;
import java.util.Optional;

/**
 * Step 20: Consultancy Management Service
 * Coordinates student consultation requests, faculty approvals/declines,
 * and automatic synchronization with the university calendar.
 */
public class ConsultancyService {
    private static ConsultancyService instance;
    private final ConsultancyRepository consultancyRepository = new ConsultancyRepository();
    private final CalendarService calendarService = CalendarService.getInstance();

    private ConsultancyService() {}

    public static synchronized ConsultancyService getInstance() {
        if (instance == null) {
            instance = new ConsultancyService();
        }
        return instance;
    }

    /**
     * Submits a new consultation booking request from a student to a teacher
     */
    public ConsultancyRequest requestConsultancy(int studentId, String studentName,
                                                 int teacherId, String teacherName,
                                                 LocalDate date, LocalTime startTime, LocalTime endTime,
                                                 String topic) {
        if (topic == null || topic.trim().isEmpty()) {
            throw new IllegalArgumentException("Consultation topic cannot be empty.");
        }
        if (date == null || startTime == null || endTime == null) {
            throw new IllegalArgumentException("Consultation date and time must be provided.");
        }
        if (endTime.isBefore(startTime) || endTime.equals(startTime)) {
            throw new IllegalArgumentException("End time must be after start time.");
        }

        ConsultancyRequest request = new ConsultancyRequest(
                0, // ID generated by repository
                studentId, studentName,
                teacherId, teacherName,
                date, startTime, endTime,
                topic.trim()
        );

        consultancyRepository.save(request);
        return request;
    }

    /**
     * Approves a consultancy request:
     * Updates status to APPROVED and automatically generates a CalendarEvent
     * placed on BOTH the student's and teacher's schedule.
     */
    public boolean approveRequest(int requestId, String teacherNote) {
        Optional<ConsultancyRequest> opt = consultancyRepository.findById(requestId);
        if (!opt.isPresent()) return false;

        ConsultancyRequest req = opt.get();
        req.setStatus(ConsultancyRequest.Status.APPROVED);
        req.setResponseNote(teacherNote != null && !teacherNote.trim().isEmpty()
                ? teacherNote.trim() : "Approved. Please attend faculty office.");

        // Create the synchronized CalendarEvent
        int nextId = DataStore.getInstance().getNextEventId();
        String eventTitle = "Consultancy: " + req.getTopic();
        String description = "Student: " + req.getStudentName() + "\nFaculty: " + req.getTeacherName()
                + "\nNote: " + req.getResponseNote();

        CalendarEvent event = new CalendarEvent(
                nextId,
                eventTitle,
                description,
                EventType.CONSULTANCY,
                req.getDate(),
                req.getStartTime(),
                req.getEndTime(),
                null,
                req.getTeacherId(),
                req.getStudentId(),
                "Faculty Office",
                null
        );

        // Direct store injection bypasses permission checks as this is an automated system sync
        DataStore.getInstance().getEvents().put(event.getId(), event);
        req.setCalendarEventId(event.getId());

        consultancyRepository.update(req);
        DataStore.getInstance().saveToFile();
        return true;
    }

    /**
     * Declines a consultancy request with an optional explanation note
     */
    public boolean declineRequest(int requestId, String reason) {
        Optional<ConsultancyRequest> opt = consultancyRepository.findById(requestId);
        if (!opt.isPresent()) return false;

        ConsultancyRequest req = opt.get();
        req.setStatus(ConsultancyRequest.Status.DECLINED);
        req.setResponseNote(reason != null && !reason.trim().isEmpty() ? reason.trim() : "Faculty unavailable at requested time.");

        // If an event was previously generated, remove it from the calendar
        if (req.getCalendarEventId() != null) {
            DataStore.getInstance().getEvents().remove(req.getCalendarEventId());
            req.setCalendarEventId(null);
        }

        consultancyRepository.update(req);
        DataStore.getInstance().saveToFile();
        return true;
    }

    /**
     * Returns all consultancy requests
     */
    public List<ConsultancyRequest> getAllRequests() {
        return consultancyRepository.findAll();
    }

    /**
     * Returns requests created by a specific student
     */
    public List<ConsultancyRequest> getRequestsForStudent(int studentId) {
        return consultancyRepository.findByStudentId(studentId);
    }

    /**
     * Returns all requests directed to a specific teacher
     */
    public List<ConsultancyRequest> getRequestsForTeacher(int teacherId) {
        return consultancyRepository.findByTeacherId(teacherId);
    }

    /**
     * Returns only pending requests for a specific teacher
     */
    public List<ConsultancyRequest> getPendingRequestsForTeacher(int teacherId) {
        return consultancyRepository.findPendingByTeacherId(teacherId);
    }

    /**
     * Returns count of pending requests for a teacher (used for badges)
     */
    public int getPendingCountForTeacher(int teacherId) {
        return getPendingRequestsForTeacher(teacherId).size();
    }

    /**
     * Query requests based on the current user's role
     */
    public List<ConsultancyRequest> getRequestsForUser(User user) {
        if (user == null || user.getRole() == Role.ADMIN) {
            return getAllRequests();
        }
        if (user.getRole() == Role.TEACHER) {
            return getRequestsForTeacher(user.getId());
        }
        return getRequestsForStudent(user.getId());
    }
}
